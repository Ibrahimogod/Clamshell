        0x53: 0x47, 0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C,
        0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57, 0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B,
        0x61: 0x5C, 0x62: 0x52, 0x63: 0x41, 0x67: 0x51, 0x85: 0x5F,
        // ISO § key (non-US \), F13–F20
        0x64: 0x0A, 0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A, 0x6C: 0x40, 0x6D: 0x4F, 0x6E: 0x50, 0x6F: 0x5A,
        // Mute, Volume up/down (as keys), JIS: ろ, ¥, かな, 英数
        0x7F: 0x4A, 0x80: 0x48, 0x81: 0x49, 0x87: 0x5E, 0x89: 0x5D, 0x90: 0x68, 0x91: 0x66,
        // Modifiers
        0xE0: 0x3B, 0xE1: 0x38, 0xE2: 0x3A, 0xE3: 0x37, 0xE4: 0x3E, 0xE5: 0x3C, 0xE6: 0x3D, 0xE7: 0x36,
        HIDUsage.function: 0x3F,
    ]

    public static func virtualKey(usage: UInt16) -> UInt16? { table[usage] }

    /// The modifier bits in the order the Mac reconciles them, with their key codes.
    public static let modifierKeys: [(KeyModifiers, UInt16)] = [
        (.leftControl, 0x3B), (.leftShift, 0x38), (.leftOption, 0x3A), (.leftCommand, 0x37),
        (.rightControl, 0x3E), (.rightShift, 0x3C), (.rightOption, 0x3D), (.rightCommand, 0x36),
        (.capsLock, 0x39), (.function, 0x3F),
    ]
}

/// Media and system keys (HID consumer page), as on a MacBook's top row.
public enum MediaKey: UInt16, Sendable, CaseIterable {
    case brightnessUp = 0x6F, brightnessDown = 0x70
    case play = 0xCD, next = 0xB5, previous = 0xB6
    case mute = 0xE2, volumeUp = 0xE9, volumeDown = 0xEA
    case missionControl = 0x29F, spotlight = 0x221, launchpad = 0x2A2
    case keyboardBrightnessUp = 0x79, keyboardBrightnessDown = 0x7A
}
