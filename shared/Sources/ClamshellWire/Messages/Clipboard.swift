/// Clipboard sync (protocol 1.2, capability `clipboardV1`, off by default on both sides). Either side
/// sends its clipboard when it changes; it travels as a bulk transfer (reliable, chunked). Text and images
/// only, ≤ 4 MiB in all. Like everything else it is inside the session encryption.
public struct ClipboardItem: Equatable, Sendable {
    /// A uniform type identifier, e.g. `public.utf8-plain-text`, `public.png`.
    public var uti: String
    public var data: [UInt8]
    public init(uti: String, data: [UInt8]) { self.uti = uti; self.data = data }
}

public struct ClipboardOffer: WireMessage {
    public static let channel = Channel.clipboard
    public static let type = MessageType.clipboardOffer

    public var items: [ClipboardItem]
    /// The sender's pasteboard change count, so the receiver doesn't echo it back.
    public var changeCount: UInt64

    public init(items: [ClipboardItem], changeCount: UInt64) { self.items = items; self.changeCount = changeCount }

    public func encodeBody() -> [UInt8] {
        var t = TLVWriter()
        t.uint(1, changeCount)
        for item in items {
            var i = TLVWriter()
            i.string(1, item.uti)
            i.bytes(2, item.data)
            t.bytes(2, i.bytes)
        }
        return t.bytes
    }

    public init(body: [UInt8]) throws {
        let t = try TLVReader(body, knownTags: [1, 2])
        changeCount = try t.optionalUInt(1) ?? 0
        items = try t.all(2).map { b in
            let i = try TLVReader(b, knownTags: [1, 2])
            return ClipboardItem(uti: try i.requiredString(1), data: try i.requiredBytes(2))
        }
    }

    public var text: String? {
        items.first { $0.uti == "public.utf8-plain-text" }.flatMap { String(validating: $0.data, as: UTF8.self) }
    }
}

/// What the Mac's clipboard sync leaves alone (M5). Password managers mark secrets with the
/// nspasteboard.org types; those, transient and auto-generated items never leave the Mac.
public enum ClipboardPolicy {
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Text above this is not synced (a log file, not a snippet).
    public static let maxTextBytes = 1 << 20
    /// Images above this are not synced.
    public static let maxImageBytes = 8 << 20

    public static func shouldSkip(types: [String]) -> Bool { types.contains { skippedTypes.contains($0) } }

    /// The items that may be sent, under the caps.
    public static func filter(_ items: [ClipboardItem]) -> [ClipboardItem] {
        items.filter { $0.uti == "public.utf8-plain-text" ? $0.data.count <= maxTextBytes : $0.data.count <= maxImageBytes }
    }
}

/// Phone → Mac (1.4, `filesV1`): a file dropped on the Mac's picture, saved to the Mac's Downloads.
/// Sent as one bulk transfer (≤ 32 MiB); `sha256` lets the Mac refuse a corrupted file.
public struct FileOffer: WireMessage {
    public static let channel = Channel.control
    public static let type = MessageType.fileOffer
    /// What fits in one bulk transfer, with room for the header.
    public static let maxBytes = BulkSender.maxBytes - 4096

    public var name: String
    public var sha256: [UInt8]
    public var data: [UInt8]

    public init(name: String, sha256: [UInt8], data: [UInt8]) {
        self.name = name
        self.sha256 = sha256
        self.data = data
    }

    public func encodeBody() -> [UInt8] {
        var t = TLVWriter()
        t.string(1, name)
        t.bytes(2, sha256)
        t.bytes(3, data)
        return t.bytes
    }

    public init(body: [UInt8]) throws {
        let t = try TLVReader(body, knownTags: [1, 2, 3])
        name = try t.requiredString(1)
        sha256 = try t.requiredBytes(2)
        data = try t.requiredBytes(3)
        guard sha256.count == 32 else { throw WireError.invalidValue("sha256 length \(sha256.count)") }
    }

    /// A name safe to create in Downloads: the last path component, no leading dots, no control or path
    /// characters, at most 200 bytes; "file" if nothing is left.
    public static func safeName(_ raw: String) -> String {
        let last = raw.split(whereSeparator: { $0 == "/" || $0 == "\\" }).last.map(String.init) ?? ""
        var cleaned = String(last.unicodeScalars.filter { !CharacterSetLite.isControl($0) && $0 != ":" }.map(Character.init))
        while cleaned.hasPrefix(".") { cleaned.removeFirst() }
        cleaned = cleaned.trimmingSpaces()
        if cleaned.utf8.count > 200 {
            // Keep the extension; shorten the stem.
            let dot = cleaned.lastIndex(of: ".")
            let ext = dot.map { String(cleaned[$0...]) } ?? ""
            var stem = dot.map { String(cleaned[..<$0]) } ?? cleaned
            while stem.utf8.count + ext.utf8.count > 200, !stem.isEmpty { stem.removeLast() }
            cleaned = ext.utf8.count > 200 ? String(stem) : stem + ext
        }
        return cleaned.isEmpty ? "file" : cleaned
    }
}

enum CharacterSetLite {
    static func isControl(_ s: Unicode.Scalar) -> Bool { s.value < 0x20 || (0x7F...0x9F).contains(s.value) || s.value == 0x200E || s.value == 0x200F || (0x202A...0x202E).contains(s.value) }
}

extension String {
    func trimmingSpaces() -> String {
        var s = Substring(self)
        while s.first?.isWhitespace == true { s.removeFirst() }
        while s.last?.isWhitespace == true { s.removeLast() }
        return String(s)
    }
}
